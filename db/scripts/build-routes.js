/*
   scripts/build-routes.js - list every endpoint file in server/ for the single Vercel function

   Run from the repo root:   npm run routes      (also runs before "npm run build")

   Writes lib/routes.generated.js. The list uses plain require('...') lines on purpose:
   Vercel only packs the files (and the packages they use) that it can see from api/index.js,
   and it can see plain require lines. Commit the generated file. Run this again whenever an
   endpoint file is added, renamed or removed; "npm test" fails if the file is out of date.
*/
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const SERVER_DIR = 'server';
const OUT_FILE = path.join('lib', 'routes.generated.js');

function walk(dir) {
  const files = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...walk(full));
    else if (entry.isFile() && entry.name.endsWith('.js')) files.push(full);
  }
  return files;
}

// 'orders/[id].js' -> 'orders/[id]'; 'orders/index.js' -> 'orders'; 'index.js' -> ''
function patternFor(rel) {
  const noExt = rel.replace(/\.js$/, '');
  const parts = noExt.split('/');
  if (parts[parts.length - 1] === 'index') parts.pop();
  return parts.join('/');
}

function listRoutes(rootDir = root) {
  const base = path.join(rootDir, SERVER_DIR);
  if (!fs.existsSync(base)) throw new Error(`There is no ${SERVER_DIR}/ folder in ${rootDir}.`);
  const byPattern = new Map();
  const problems = [];
  for (const full of walk(base).sort()) {
    const rel = path.relative(base, full).split(path.sep).join('/');
    if (/\[\.\.\./.test(rel)) {
      problems.push(`${rel}: catch-all file names ([...x]) are not supported inside ${SERVER_DIR}/`);
      continue;
    }
    const pattern = patternFor(rel);
    const existing = byPattern.get(pattern);
    // products.js and products/index.js both mean /api/products: the plain file wins, like in npm start.
    if (existing) {
      const keep = existing.endsWith('/index.js') || existing === 'index.js' ? rel : existing;
      problems.push(`${existing} and ${rel} both answer /api/${pattern}; using ${keep}`);
      byPattern.set(pattern, keep);
    } else {
      byPattern.set(pattern, rel);
    }
  }
  const routes = [...byPattern.entries()]
    .map(([pattern, rel]) => ({ pattern, rel }))
    .sort((a, b) => a.pattern.localeCompare(b.pattern));
  return { routes, problems };
}

function manifestText(rootDir = root) {
  const { routes, problems } = listRoutes(rootDir);
  const lines = routes.map(
    ({ pattern, rel }) =>
      `  { pattern: ${JSON.stringify(pattern)}, load: () => require(${JSON.stringify(`../${SERVER_DIR}/${rel}`)}) },`
  );
  const text = [
    '// GENERATED by scripts/build-routes.js. Do not edit by hand: run "npm run routes".',
    '// One line per endpoint file in server/. See lib/router.js for why.',
    'module.exports = [',
    ...lines,
    '];',
    '',
  ].join('\n');
  return { text, routes, problems };
}

module.exports = { listRoutes, manifestText, patternFor };

if (require.main === module) {
  const { text, routes, problems } = manifestText();
  fs.writeFileSync(path.join(root, OUT_FILE), text);
  console.log(`Wrote ${OUT_FILE} with ${routes.length} endpoint(s):`);
  for (const r of routes) console.log(`  /api/${r.pattern}`.padEnd(40) + `-> ${SERVER_DIR}/${r.rel}`);
  if (problems.length) {
    console.log('\nCheck these:');
    for (const p of problems) console.log(`  ${p}`);
    process.exitCode = problems.some((p) => /not supported/.test(p)) ? 1 : 0;
  }
}
